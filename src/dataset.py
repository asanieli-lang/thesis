import os
import bisect
import logging
import torch
from torch.utils.data import Dataset

logger = logging.getLogger(__name__)

class MyDataset(Dataset):
    """
    PyTorch Dataset for loading batched EEG windows.
    Reads directly from the batched .pt files generated by the preprocessor.
    """
    
    def __init__(self, data_dir: str):
        """
        Args:
            data_dir: Path to the directory containing _processed.pt files.
        """
        self.data_dir = data_dir
        self.files = sorted([
            os.path.join(data_dir, f) for f in os.listdir(data_dir) 
            if f.endswith('.pt')
        ])
        
        self.cumulative_lengths = []
        total_samples = 0
        
        print(f"Scanning {len(self.files)} data files...")
        
        # Quickly scan all files to determine the global index
        for f in self.files:
            data = torch.load(f, map_location='cpu', weights_only=True)
            length = len(data['labels'])
            total_samples += length
            self.cumulative_lengths.append(total_samples)
            
        print(f"Dataset successfully indexed {total_samples} total EEG windows.")

    def __len__(self) -> int:
        return self.cumulative_lengths[-1] if self.cumulative_lengths else 0

    def __getitem__(self, idx: int) -> tuple[torch.Tensor, int]:
        # 1. Find which file contains this global index
        file_idx = bisect.bisect_right(self.cumulative_lengths, idx)
        
        # 2. Calculate the local index inside that specific file
        if file_idx == 0:
            local_idx = idx
        else:
            local_idx = idx - self.cumulative_lengths[file_idx - 1]
            
        # 3. Load the data using Memory Mapping (mmap=True) for speed
        file_path = self.files[file_idx]
        data = torch.load(file_path, map_location='cpu', mmap=True, weights_only=True)
        
        # 4. Extract the specific 4-second tensor and label
        signal = data['signals'][local_idx]
        label = data['labels'][local_idx]
        
        return signal, int(label)